function uniqueSorted(values) {
  return [...new Set(values)].sort()
}

function writeGenerated(path, body) {
  writeFileSync(
    path,
    `// Generated by scripts/generate-languages.mjs. Do not edit by hand.\n${body}`,
    'utf8',
  )
}

function makeModule(canonical, moduleId) {
  return `  ${JSON.stringify(canonical)}: () => import(${JSON.stringify(moduleId)}),`
}

function buildFile({ entries, aliases, sourceNote }) {
  const languages = uniqueSorted(entries.map(([canonical]) => canonical))
  const aliasEntries = Object.entries(aliases)
    .filter(([alias, target]) => !languages.includes(alias) && languages.includes(target))
    .sort(([a], [b]) => a.localeCompare(b))
  return `${sourceNote}
export const languageLoaders = {
${entries
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([canonical, moduleId]) => makeModule(canonical, moduleId))
  .join('\n')}
} satisfies Record<string, () => Promise<unknown>>

export const languageAliases: Readonly<Record<string, string>> = {
${aliasEntries.map(([alias, target]) => `  ${JSON.stringify(alias)}: ${JSON.stringify(target)},`).join('\n')}
}

export const supportedLanguages: readonly string[] = ${JSON.stringify(languages)}
`
}

async function shikiEntries() {
  const { bundledLanguagesInfo } = await import('shiki/langs')
  const info = new Map(bundledLanguagesInfo.map((entry) => [entry.id, entry]))
  const sourceMap = {
    bash: 'shellscript',
    dockerfile: 'docker',
    makefile: 'make',
    fortran: 'fortran-free-form',
  }
  const entries = []
  const aliases = { ...COMMON_ALIASES }
  for (const canonical of CANONICAL) {
    const id = sourceMap[canonical] ?? canonical
    if (!info.has(id)) continue
    entries.push([canonical, `shiki/langs/${id}.mjs`])
    for (const alias of info.get(id)?.aliases ?? []) {
      aliases[alias] = canonical
    }
  }
  return { entries, aliases }
}

function refractorEntries() {
  const directory = join(process.cwd(), 'node_modules/refractor/lang')
  const available = new Set(
    readdirSync(directory)
      .filter((file) => file.endsWith('.js'))
      .map((file) => file.slice(0, -3)),
  )
  const sourceMap = {
    shellscript: 'bash',
    docker: 'docker',
    make: 'makefile',
    'objective-c': 'objectivec',
    html: 'markup',
  }
  const entries = []
  for (const canonical of CANONICAL) {
    const id = sourceMap[canonical] ?? canonical
    if (available.has(id)) entries.push([canonical, `refractor/${id}`])
  }
  return { entries, aliases: { ...COMMON_ALIASES } }
}

function highlightjsEntries() {
  const directory = join(process.cwd(), 'node_modules/highlight.js/lib/languages')
  const available = new Set(
    readdirSync(directory)
      .filter((file) => file.endsWith('.js') && !file.endsWith('.js.js'))
      .map((file) => file.replace(/\.js$/, '')),
  )
  const sourceMap = {
    shellscript: 'bash',
    docker: 'dockerfile',
    make: 'makefile',
    'objective-c': 'objectivec',
    html: 'xml',
  }
  const entries = []
  for (const canonical of CANONICAL) {
    const id = sourceMap[canonical] ?? canonical
    if (available.has(id)) entries.push([canonical, `highlight.js/lib/languages/${id}`])
  }
  return { entries, aliases: { ...COMMON_ALIASES, html: 'html' } }
}

